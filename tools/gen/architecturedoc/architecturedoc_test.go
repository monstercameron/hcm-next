func TestTodo_ARCH_GO_028_Conformance(t *testing.T) {
	s := Snapshot{Module: "fixture.test", Packages: []Package{{ImportPath: "fixture.test/b"}, {ImportPath: "fixture.test/a"}}, Edges: []Edge{{Importer: "fixture.test/b", Imported: "fixture.test/a"}}}
	doc := string(Render(s))
	if strings.Index(doc, "fixture.test/a") > strings.Index(doc, "fixture.test/b") {
		t.Fatal("package order is not canonical")
	}
	if !strings.Contains(doc, "fixture.test/b -> fixture.test/a") {
		t.Fatal("edge missing")
	}
}

func TestTodo_ARCH_GO_028_Property(t *testing.T) {
	base := Snapshot{Module: "fixture.test", Packages: []Package{{ImportPath: "fixture.test/z"}, {ImportPath: "fixture.test/a"}}, Edges: []Edge{{Importer: "fixture.test/z", Imported: "fixture.test/a"}}, Processes: map[string][]string{"z": {"worker (initial)"}}}
	first := Render(base)
	for i := 0; i < 20; i++ {
		s := Snapshot{Module: base.Module, Digest: base.Digest, Packages: append([]Package(nil), base.Packages...), Edges: append([]Edge(nil), base.Edges...), Processes: map[string][]string{"z": {"worker (initial)"}}}
		if i%2 == 0 {
			s.Packages[0], s.Packages[1] = s.Packages[1], s.Packages[0]
		}
		if !bytes.Equal(first, Render(s)) {
			t.Fatal("render depends on input order")
		}
	}
}
