	s := Snapshot{Module: "fixture.test", Digest: "digest", Packages: []Package{{ImportPath: "fixture.test/internal/z", Root: "z", Owner: "owner-z", Layer: "domains", Phase: "P2"}, {ImportPath: "fixture.test/internal/a", Root: "a", Owner: "owner-a", Layer: "kernel", Phase: "P1A"}}, Edges: []Edge{{Importer: "fixture.test/internal/z", Imported: "fixture.test/internal/a"}}, Processes: map[string][]string{"a": {"hcmnext (initial)"}}, PortAdapters: []Boundary{{Name: "data", Root: "internal/data", Packages: []string{"fixture.test/internal/data", "fixture.test/internal/data/postgres"}}}}
