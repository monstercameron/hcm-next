package deferredschema

import (
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"
)

// DispositionRow is one row of the storage-disposition preview: the exact
// field shape internal/data/tenancy/storagedisposition.TableEntry declares
// for definitions/storage/storage-disposition.yaml, plus the one extra key
// DB-016 requires -- Disposition (DRAFT or CONFORMANCE) -- that marks the row
// as not-yet-authoritative. A real storagedisposition.TableEntry is never
// imported here: this package must stay independent of the live registry's
// package so a preview row can never be mistaken for -- or accidentally
// merged into -- the live one.
type DispositionRow struct {
	Table               string   `yaml:"table"`
	Migration           string   `yaml:"migration"`
	OwnerPackage        string   `yaml:"owner_package"`
	Plane               string   `yaml:"plane"`
	DataRole            string   `yaml:"data_role"`
	TenantScopingColumn *string  `yaml:"tenant_scoping_column"`
	IsolationPackage    string   `yaml:"isolation_package"`
	AppendOnly          bool     `yaml:"append_only"`
	RetentionClass      string   `yaml:"retention_class"`
	EncryptionClass     string   `yaml:"encryption_class"`
	RebuildSource       *string  `yaml:"rebuild_source"`
	Partitions          []string `yaml:"partitions"`
	Notes               string   `yaml:"notes"`
	// Disposition is the one field beyond the live registry's row shape:
	// DRAFT or CONFORMANCE. See doc.go for the rule that assigns it.
	Disposition string `yaml:"disposition"`
}

// dispositionRowsForTable builds the two rows (Head, Evidence) for one
// domain in fixed order.
func dispositionRowsForDomain(d Domain) []DispositionRow {
	tenantCol := "tenant_id"
	rows := make([]DispositionRow, 0, 2)
	for _, t := range d.Tables() {
		rows = append(rows, DispositionRow{
			Table:               t.Table,
			Migration:           d.PreviewFileName(),
			OwnerPackage:        "internal/domains/" + d.Slug,
			Plane:               "DATA",
			DataRole:            t.DataRole,
			TenantScopingColumn: &tenantCol,
			IsolationPackage:    "internal/data/tenancy",
			AppendOnly:          t.AppendOnly,
			RetentionClass:      t.RetentionClass,
			EncryptionClass:     "PLATFORM_MANAGED",
			RebuildSource:       nil,
			Partitions:          nil,
			Notes:               t.Notes,
			Disposition:         d.Disposition,
		})
	}
	return rows
}

// DispositionRows returns every preview row across all ten domains, in fixed
// domain/table order (deterministic; never sorted or map-derived).
func DispositionRows(domains []Domain) []DispositionRow {
	var rows []DispositionRow
	for _, d := range domains {
		rows = append(rows, dispositionRowsForDomain(d)...)
	}
	return rows
}

// dispositionPreviewDoc is the top-level shape of
// testdata/preview/storage-disposition.deferred.yaml: the same
// version/module header definitions/storage/storage-disposition.yaml uses,
// plus its Tables list carrying the extra disposition key.
type dispositionPreviewDoc struct {
	Version int              `yaml:"version"`
	Module  string           `yaml:"module"`
	Source  string           `yaml:"source"`
	Tables  []DispositionRow `yaml:"tables"`
}

// RenderDispositionPreviewYAML renders the full disposition preview file for
// every domain, byte-deterministic across calls.
func RenderDispositionPreviewYAML(domains []Domain) (string, error) {
	doc := dispositionPreviewDoc{
		Version: 1,
		Module:  "github.com/monstercameron/human-capital-management-suite",
		Source:  "planning/data/models (payroll, benefits, time, leave, recruiting, talent, learning, case, access, regulatory)",
		Tables:  DispositionRows(domains),
	}

	var header strings.Builder
	header.WriteString("# PREVIEW ONLY (DB-016): generated by tools/gen/deferredschema.\n")
	header.WriteString("#\n")
	header.WriteString("# Same row shape as definitions/storage/storage-disposition.yaml (loaded by\n")
	header.WriteString("# internal/data/tenancy/storagedisposition), plus one extra key per row:\n")
	header.WriteString("# disposition, which is DRAFT or CONFORMANCE -- never a real retention/plane\n")
	header.WriteString("# value the live registry would accept, so this file can never be swapped in\n")
	header.WriteString("# for the live one by accident. No table named here exists in\n")
	header.WriteString("# definitions/storage/storage-disposition.yaml, in migrations/, or as a write\n")
	header.WriteString("# in the Phase 1 capability registry (internal/capability); validate.go proves\n")
	header.WriteString("# all three.\n\n")

	body, err := yaml.Marshal(doc)
	if err != nil {
		return "", fmt.Errorf("deferredschema: marshal disposition preview: %w", err)
	}

	return header.String() + string(body), nil
}

// LoadDispositionPreviewYAML parses a disposition preview file's bytes back
// into rows, for the validator to check.
func LoadDispositionPreviewYAML(data []byte) ([]DispositionRow, error) {
	var doc dispositionPreviewDoc
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("deferredschema: parse disposition preview: %w", err)
	}
	return doc.Tables, nil
}
