package deferredschema

import (
	"fmt"
	"strings"
)

// PreviewFileName returns the migration preview's file name (NNN_<slug>.sql),
// matching migrations/'s NNNNN_name.sql shape but placed under
// testdata/preview so it never lands in the applied migration tree.
func (d Domain) PreviewFileName() string {
	return fmt.Sprintf("%03d_%s.sql", d.Number, d.Slug)
}

// Tables returns the domain's Head and Evidence table specs together.
func (d Domain) Tables() []TableSpec {
	return []TableSpec{d.Head, d.Evidence}
}

// RenderMigrationPreview renders the domain's full goose-shaped migration
// preview: a header explaining its DRAFT/CONFORMANCE disposition and both
// tables, each with row-level security and (for the Evidence table) a
// forbid_mutation trigger, matching migrations/00023_journey_workforce.sql's
// house convention.
func RenderMigrationPreview(d Domain) string {
	var b strings.Builder

	fmt.Fprintf(&b, "-- PREVIEW ONLY (DB-016): generated by tools/gen/deferredschema. Not applied by\n")
	fmt.Fprintf(&b, "-- goose and never copied into migrations/ until %s domain's own funded\n", d.Title)
	fmt.Fprintf(&b, "-- authority-gate todo lands. Disposition: %s.\n", d.Disposition)
	fmt.Fprintf(&b, "-- %s\n", d.DispositionReason)
	fmt.Fprintf(&b, "-- Source: %s %s.\n", d.SourceDoc, d.SourceSection)
	fmt.Fprintf(&b, "--\n")
	fmt.Fprintf(&b, "-- %s\n", d.Head.Notes)
	fmt.Fprintf(&b, "-- %s\n", d.Evidence.Notes)
	b.WriteString("\n-- +goose Up\n\n")

	b.WriteString(renderHeadTable(d.Head))
	b.WriteString("\n")
	b.WriteString(renderEvidenceTable(d.Evidence, d.Head))

	b.WriteString("\n-- +goose Down\n")
	fmt.Fprintf(&b, "REVOKE ALL ON %s FROM hcmnext_app;\n", d.Evidence.Table)
	fmt.Fprintf(&b, "DROP POLICY tenant_isolation ON %s;\n", d.Evidence.Table)
	fmt.Fprintf(&b, "ALTER TABLE %s NO FORCE ROW LEVEL SECURITY;\n", d.Evidence.Table)
	fmt.Fprintf(&b, "ALTER TABLE %s DISABLE ROW LEVEL SECURITY;\n", d.Evidence.Table)
	fmt.Fprintf(&b, "DROP TABLE %s;\n\n", d.Evidence.Table)
	fmt.Fprintf(&b, "REVOKE ALL ON %s FROM hcmnext_app;\n", d.Head.Table)
	fmt.Fprintf(&b, "DROP POLICY tenant_isolation ON %s;\n", d.Head.Table)
	fmt.Fprintf(&b, "ALTER TABLE %s NO FORCE ROW LEVEL SECURITY;\n", d.Head.Table)
	fmt.Fprintf(&b, "ALTER TABLE %s DISABLE ROW LEVEL SECURITY;\n", d.Head.Table)
	fmt.Fprintf(&b, "DROP TABLE %s;\n", d.Head.Table)

	return b.String()
}

func renderColumn(c Column) string {
	if c.Default == "" {
		return fmt.Sprintf("    %-24s %s NOT NULL", c.Name, c.Type)
	}
	return fmt.Sprintf("    %-24s %s NOT NULL DEFAULT %s", c.Name, c.Type, c.Default)
}

func renderHeadTable(t TableSpec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE TABLE IF NOT EXISTS %s (\n", t.Table)
	fmt.Fprintf(&b, "    tenant_id                tenant_ref   NOT NULL REFERENCES tenant (tenant_id),\n")
	fmt.Fprintf(&b, "    %-24s uuid         NOT NULL,\n", t.IDColumn)
	fmt.Fprintf(&b, "    %-24s semantic_key NOT NULL,\n", t.KeyColumn)
	for _, c := range t.Columns {
		b.WriteString(renderColumn(c))
		b.WriteString(",\n")
	}
	b.WriteString("    effective_from           date         NOT NULL,\n")
	b.WriteString("    known_at                 timestamptz  NOT NULL,\n")
	b.WriteString("    recorded_at              timestamptz  NOT NULL DEFAULT now(),\n")
	b.WriteString("\n")
	fmt.Fprintf(&b, "    PRIMARY KEY (tenant_id, %s),\n", t.IDColumn)
	fmt.Fprintf(&b, "    CONSTRAINT %s_key_unique UNIQUE (tenant_id, %s),\n", t.Table, t.KeyColumn)
	for _, chk := range t.CheckConstraints {
		fmt.Fprintf(&b, "    CONSTRAINT %s_check CHECK (%s),\n", constraintSlug(t.Table, chk), chk)
	}
	fmt.Fprintf(&b, "    CONSTRAINT %s_knowledge_order CHECK (known_at <= recorded_at)\n", t.Table)
	b.WriteString(");\n\n")

	fmt.Fprintf(&b, "CREATE INDEX IF NOT EXISTS %s_recorded\n", t.Table)
	fmt.Fprintf(&b, "    ON %s (tenant_id, recorded_at DESC);\n\n", t.Table)

	b.WriteString(renderTenantIsolation(t.Table))
	fmt.Fprintf(&b, "GRANT SELECT, INSERT, UPDATE ON %s TO hcmnext_app;\n", t.Table)
	return b.String()
}

func renderEvidenceTable(t TableSpec, parent TableSpec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "CREATE TABLE IF NOT EXISTS %s (\n", t.Table)
	fmt.Fprintf(&b, "    tenant_id                tenant_ref   NOT NULL REFERENCES tenant (tenant_id),\n")
	fmt.Fprintf(&b, "    %-24s uuid         NOT NULL,\n", t.IDColumn)
	fmt.Fprintf(&b, "    %-24s uuid         NOT NULL,\n", t.ParentIDColumn)
	b.WriteString("    revision_sequence        bigint       NOT NULL,\n")
	for _, c := range t.Columns {
		b.WriteString(renderColumn(c))
		b.WriteString(",\n")
	}
	b.WriteString("    known_at                 timestamptz  NOT NULL,\n")
	b.WriteString("    recorded_at              timestamptz  NOT NULL DEFAULT now(),\n")
	b.WriteString("\n")
	fmt.Fprintf(&b, "    PRIMARY KEY (tenant_id, %s),\n", t.IDColumn)
	fmt.Fprintf(&b, "    CONSTRAINT %s_revision_positive CHECK (revision_sequence >= 1),\n", t.Table)
	for _, chk := range t.CheckConstraints {
		fmt.Fprintf(&b, "    CONSTRAINT %s_check CHECK (%s),\n", constraintSlug(t.Table, chk), chk)
	}
	fmt.Fprintf(&b, "    CONSTRAINT %s_knowledge_order CHECK (known_at <= recorded_at),\n", t.Table)
	fmt.Fprintf(&b, "    FOREIGN KEY (tenant_id, %s) REFERENCES %s (tenant_id, %s)\n",
		t.ParentIDColumn, parent.Table, parent.IDColumn)
	b.WriteString(");\n\n")

	fmt.Fprintf(&b, "CREATE INDEX IF NOT EXISTS %s_recorded\n", t.Table)
	fmt.Fprintf(&b, "    ON %s (tenant_id, recorded_at DESC);\n\n", t.Table)

	fmt.Fprintf(&b, "CREATE OR REPLACE TRIGGER %s_append_only\n", t.Table)
	fmt.Fprintf(&b, "    BEFORE UPDATE OR DELETE ON %s\n", t.Table)
	b.WriteString("    FOR EACH ROW EXECUTE FUNCTION forbid_mutation();\n\n")
	fmt.Fprintf(&b, "REVOKE UPDATE, DELETE ON %s FROM PUBLIC;\n\n", t.Table)

	b.WriteString(renderTenantIsolation(t.Table))
	fmt.Fprintf(&b, "GRANT SELECT, INSERT ON %s TO hcmnext_app;\n", t.Table)
	return b.String()
}

func renderTenantIsolation(table string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", table)
	fmt.Fprintf(&b, "ALTER TABLE %s FORCE ROW LEVEL SECURITY;\n", table)
	fmt.Fprintf(&b, "CREATE POLICY tenant_isolation ON %s\n", table)
	b.WriteString("    USING (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)\n")
	b.WriteString("    WITH CHECK (tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid);\n")
	return b.String()
}

// constraintSlug turns a CHECK clause into a short, stable constraint-name
// suffix (first token of the clause, lower-cased, non-alnum stripped).
func constraintSlug(table, clause string) string {
	fields := strings.FieldsFunc(clause, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_')
	})
	if len(fields) == 0 {
		return table + "_extra"
	}
	return table + "_" + strings.ToLower(fields[0])
}

// UpSQL extracts the -- +goose Up .. -- +goose Down body from a rendered (or
// on-disk) migration preview, for direct execution against a test database
// (this package's own DDL is never driven through goose).
func UpSQL(preview string) string {
	start := strings.Index(preview, "-- +goose Up")
	if start < 0 {
		return ""
	}
	body := preview[start+len("-- +goose Up"):]
	if end := strings.Index(body, "-- +goose Down"); end >= 0 {
		body = body[:end]
	}
	return body
}

// Statements splits a SQL body into individual, semicolon-terminated
// statements, dropping blank/comment-only segments. It is a plain string
// split, which is sufficient for every statement this package generates
// (none contain a semicolon inside a string literal or a dollar-quoted
// body).
func Statements(sql string) []string {
	raw := strings.Split(sql, ";")
	var out []string
	for _, stmt := range raw {
		trimmed := strings.TrimSpace(stripSQLComments(stmt))
		if trimmed == "" {
			continue
		}
		out = append(out, trimmed)
	}
	return out
}

func stripSQLComments(s string) string {
	lines := strings.Split(s, "\n")
	var kept []string
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "--") {
			continue
		}
		kept = append(kept, line)
	}
	return strings.Join(kept, "\n")
}
