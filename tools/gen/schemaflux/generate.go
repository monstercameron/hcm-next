package schemaflux

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// RegistrySource renders the compiled catalog as deterministic Go source: a
// package-level slice literal, one entry per definition, sorted by
// intent_type_id. It contains no timestamp, no absolute path and no
// map-iteration-dependent ordering, so two runs over the same catalog (on one
// machine or two) produce byte-identical text — that determinism is exactly
// what [TestSchemaFluxOfflineFixture] proves.
func (c *Catalog) RegistrySource(packageName string) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/gen/schemaflux. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n// Source: schema/schemaflux/business_intents/v1 (%d definitions), ", len(c.Definitions))
	fmt.Fprintf(&b, "tools/gen/schemaflux/testdata/capability_manifest.yaml (%d entries).\n", len(c.CapabilityManifest))
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	fmt.Fprintf(&b, "// GeneratedDefinition is the qualification fixture's Go projection of one\n")
	fmt.Fprintf(&b, "// compiled business-intent definition.\n")
	fmt.Fprintf(&b, "type GeneratedDefinition struct {\n")
	fmt.Fprintf(&b, "\tIntentTypeID string\n\tVersion      uint32\n\tDisplayName  string\n")
	fmt.Fprintf(&b, "\tOwnerPlane   string\n\tOwnerDomain  string\n\tKernelFamily string\n")
	fmt.Fprintf(&b, "\tInputSchema  string\n\tResultSchema string\n")
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// Definitions is the compiled catalog, in intent_type_id order.\n")
	fmt.Fprintf(&b, "var Definitions = []GeneratedDefinition{\n")
	for _, d := range c.Definitions {
		fmt.Fprintf(&b, "\t{IntentTypeID: %s, Version: %d, DisplayName: %s, OwnerPlane: %s, OwnerDomain: %s, KernelFamily: %s, InputSchema: %s, ResultSchema: %s},\n",
			strconv.Quote(d.IntentTypeID), d.Version, strconv.Quote(d.DisplayName),
			strconv.Quote(d.OwnerPlane), strconv.Quote(d.OwnerDomain), strconv.Quote(d.KernelFamily),
			strconv.Quote(d.InputSchemaRef), strconv.Quote(d.ResultSchemaRef))
	}
	fmt.Fprintf(&b, "}\n")
	return []byte(b.String())
}

// CatalogMarkdown renders the compiled catalog as a human-readable table,
// sorted the same way as RegistrySource for the same determinism guarantee.
func (c *Catalog) CatalogMarkdown() []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# Business intent catalog (generated)\n\n")
	fmt.Fprintf(&b, "Generated by tools/gen/schemaflux from schema/schemaflux/business_intents/v1 ")
	fmt.Fprintf(&b, "and tools/gen/schemaflux/testdata/capability_manifest.yaml. Do not edit by hand.\n\n")
	fmt.Fprintf(&b, "%d definitions, %d P1A capability manifest entries.\n\n", len(c.Definitions), len(c.CapabilityManifest))
	fmt.Fprintf(&b, "| intent_type_id | version | display_name | owner_plane | owner_domain | kernel_family |\n")
	fmt.Fprintf(&b, "| --- | --- | --- | --- | --- | --- |\n")
	for _, d := range c.Definitions {
		fmt.Fprintf(&b, "| %s | %d | %s | %s | %s | %s |\n",
			d.IntentTypeID, d.Version, d.DisplayName, d.OwnerPlane, d.OwnerDomain, d.KernelFamily)
	}
	fmt.Fprintf(&b, "\n## P1A capability manifest\n\n")
	fmt.Fprintf(&b, "| id | version | owner_domain | storage_disposition |\n")
	fmt.Fprintf(&b, "| --- | --- | --- | --- |\n")
	for _, m := range c.CapabilityManifest {
		fmt.Fprintf(&b, "| %s | %d | %s | %s |\n", m.ID, m.Version, m.OwnerDomain, m.StorageDisposition)
	}
	return []byte(b.String())
}

// fixtureDefinition and fixtureManifest are the JSON projections
// [Catalog.FixturesJSON] emits: struct field order (not map key order)
// determines JSON key order, and encoding/json never reorders struct fields,
// so this output is deterministic without any explicit sort step beyond the
// slice ordering [Compile] already established.
type fixtureDefinition struct {
	IntentTypeID string `json:"intent_type_id"`
	Version      uint32 `json:"version"`
	DisplayName  string `json:"display_name"`
	OwnerPlane   string `json:"owner_plane"`
	OwnerDomain  string `json:"owner_domain"`
	KernelFamily string `json:"kernel_family"`
	InputSchema  string `json:"input_schema"`
	ResultSchema string `json:"result_schema"`
}

type fixtureManifestEntry struct {
	ID                 string `json:"id"`
	Version            uint32 `json:"version"`
	OwnerDomain        string `json:"owner_domain"`
	StorageDisposition string `json:"storage_disposition"`
}

type fixtureFile struct {
	Definitions        []fixtureDefinition    `json:"definitions"`
	CapabilityManifest []fixtureManifestEntry `json:"capability_manifest"`
}

// FixturesJSON renders the compiled catalog as deterministic, indented JSON.
func (c *Catalog) FixturesJSON() ([]byte, error) {
	f := fixtureFile{}
	for _, d := range c.Definitions {
		f.Definitions = append(f.Definitions, fixtureDefinition{
			IntentTypeID: d.IntentTypeID, Version: d.Version, DisplayName: d.DisplayName,
			OwnerPlane: d.OwnerPlane, OwnerDomain: d.OwnerDomain, KernelFamily: d.KernelFamily,
			InputSchema: d.InputSchemaRef, ResultSchema: d.ResultSchemaRef,
		})
	}
	for _, m := range c.CapabilityManifest {
		f.CapabilityManifest = append(f.CapabilityManifest, fixtureManifestEntry{
			ID: m.ID, Version: m.Version, OwnerDomain: m.OwnerDomain, StorageDisposition: m.StorageDisposition,
		})
	}
	out, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(out, '\n'), nil
}

// Artifacts is one complete generation run's output bytes, named the way
// WriteAll names the files it writes.
type Artifacts struct {
	RegistryGo   []byte
	CatalogMD    []byte
	FixturesJSON []byte
}

// Generate produces the three qualification-fixture artifacts from a compiled
// catalog. It performs no I/O; callers compare two in-memory Generate results
// for byte-identity, or pass the result to WriteAll to persist it.
func Generate(catalog *Catalog, packageName string) (Artifacts, error) {
	fixtures, err := catalog.FixturesJSON()
	if err != nil {
		return Artifacts{}, err
	}
	return Artifacts{
		RegistryGo:   catalog.RegistrySource(packageName),
		CatalogMD:    catalog.CatalogMarkdown(),
		FixturesJSON: fixtures,
	}, nil
}

// WriteAll writes a's three artifacts under outDir as registry_generated.go,
// catalog.md and fixtures.json.
func WriteAll(a Artifacts, outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	files := map[string][]byte{
		"registry_generated.go": a.RegistryGo,
		"catalog.md":            a.CatalogMD,
		"fixtures.json":         a.FixturesJSON,
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(outDir, name), content, 0o644); err != nil {
			return err
		}
	}
	return nil
}
