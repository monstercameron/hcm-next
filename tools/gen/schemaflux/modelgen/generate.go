// Artifact is one reproducible model-generation result. SourceDigest is the
// digest of the canonical source projection; GeneratedDigest is the digest of
// the generated template with its digest marker blanked. This avoids the
// circularity of hashing a file which contains its own hash.
type Artifact struct {
	Go              []byte
	SourceDigest    string
	GeneratedDigest string
}

// CanonicalDigest hashes length-prefixed parts. It is exported so generated
// consumers and drift checks can use the same boundary-safe convention as the
// other SchemaFlux generators.
func CanonicalDigest(parts ...[]byte) string {
	h := sha256.New()
	for _, p := range parts {
		var n [8]byte
		n[0] = byte(len(p) >> 56)
		n[1] = byte(len(p) >> 48)
		n[2] = byte(len(p) >> 40)
		n[3] = byte(len(p) >> 32)
		n[4] = byte(len(p) >> 24)
		n[5] = byte(len(p) >> 16)
		n[6] = byte(len(p) >> 8)
		n[7] = byte(len(p))
		h.Write(n[:])
		h.Write(p)
	}
	return "sha256:" + hex.EncodeToString(h.Sum(nil))
}

// SourceDigest returns the digest of every source field which contributes to
// generated behavior. Ordering is explicitly normalized so filesystem order,
// map order and host paths never alter the digest.
func SourceDigest(m *sources.Manifest) string {
	return CanonicalDigest(canonicalSource(m))
}

// Generate renders a complete generated Go model package.
func Generate(m *sources.Manifest, packageName string) (Artifact, error) {
	if m == nil {
		return Artifact{}, fmt.Errorf("modelgen: nil manifest")
	}
	if packageName == "" {
		return Artifact{}, fmt.Errorf("modelgen: empty package name")
	}
	if err := ValidateManifest(m); err != nil {
		return Artifact{}, err
	}
	sd := SourceDigest(m)
	blank, err := render(m, packageName, sd, "")
	if err != nil {
		return Artifact{}, err
	}
	gd := digestBytes(blank)
	goBytes, err := render(m, packageName, sd, gd)
	if err != nil {
		return Artifact{}, err
	}
	return Artifact{Go: goBytes, SourceDigest: sd, GeneratedDigest: gd}, nil
}

// ValidateManifest is the generator's publication gate. It repeats the
// source compiler's invariants at the generation boundary so a hand-built or
// mutated manifest cannot produce an invalid lifecycle, constraint, or
// untyped modeled field.
func ValidateManifest(m *sources.Manifest) error {
	if m == nil {
		return fmt.Errorf("modelgen: nil manifest")
	}
	seenEntities := map[string]bool{}
	for _, e := range m.Entities {
		ref := e.Ref()
		if seenEntities[ref] {
			return fmt.Errorf("modelgen: duplicate entity %s", ref)
		}
		seenEntities[ref] = true
		if e.Name == "" || e.Key == "" || e.OwnerDomain == "" || e.Class == "" || e.Status == "" || e.LifecycleAssignment == "" {
			return fmt.Errorf("modelgen: incomplete entity %s", ref)
		}
		if e.Covered && e.Status != "ACTIVE" {
			return fmt.Errorf("modelgen: covered entity %s must be ACTIVE", ref)
		}
		if e.Class == "READ_MODEL" && e.LifecycleAssignment != "NO_BUSINESS_LIFECYCLE" {
			return fmt.Errorf("modelgen: read model %s has business lifecycle %q", ref, e.LifecycleAssignment)
		}
		for _, p := range e.Properties {
			if p.Name == "" || p.GoType == "" || p.SchemaPath == "" || p.Presence == "" || p.Classification == "" || p.Temporal == "" || p.AuthorityRef == "" || p.Correction == "" || p.RetentionClassRef == "" || p.Status == "" {
				return fmt.Errorf("modelgen: incomplete property %s.%s", ref, p.Name)
			}
			if strings.Contains(p.GoType, "map[") || strings.Contains(p.GoType, "any") {
				return fmt.Errorf("modelgen: untyped property %s.%s has Go type %q", ref, p.Name, p.GoType)
			}
			switch p.GoType {
			case "string", "bool", "uint32", "[]string", "lifecycle.StateID", "lifecycle.Dimensions", "values.Decimal", "values.EffectiveInterval", "values.Instant", "values.LocalDate", "values.Money", "values.Percentage", "values.Quantity":
			default:
				return fmt.Errorf("modelgen: unsupported Go type %q at %s.%s", p.GoType, ref, p.Name)
			}
		}
	}
	seenRelations := map[string]bool{}
	for _, r := range m.Relationships {
		if seenRelations[r.Ref()] {
			return fmt.Errorf("modelgen: duplicate relationship %s", r.Ref())
		}
		seenRelations[r.Ref()] = true
		if !seenEntities[r.SourceEntity] || !seenEntities[r.TargetEntity] {
			return fmt.Errorf("modelgen: relationship %s has unresolved endpoint", r.Ref())
		}
		if r.Cardinality != "ONE_TO_ONE" && r.Cardinality != "ONE_TO_MANY" && r.Cardinality != "MANY_TO_MANY" {
			return fmt.Errorf("modelgen: relationship %s has invalid cardinality %q", r.Ref(), r.Cardinality)
		}
	}
	return nil
}

// RenderGo is a convenience for callers that only need generated bytes.
func RenderGo(m *sources.Manifest, packageName string) ([]byte, error) {
	a, err := Generate(m, packageName)
	if err != nil {
		return nil, err
	}
	return a.Go, nil
}

func digestBytes(b []byte) string {
	s := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(s[:])
}

func canonicalSource(m *sources.Manifest) []byte {
	ents := append([]sources.EntitySource(nil), m.Entities...)
	sort.Slice(ents, func(i, j int) bool { return ents[i].Ref() < ents[j].Ref() })
	rels := append([]sources.RelationshipSource(nil), m.Relationships...)
	sort.Slice(rels, func(i, j int) bool { return rels[i].Ref() < rels[j].Ref() })
	auth := append([]sources.AuthoritySource(nil), m.Authorities...)
	sort.Slice(auth, func(i, j int) bool { return auth[i].Ref < auth[j].Ref })
	ret := append([]sources.RetentionClassSource(nil), m.Retentions...)
	sort.Slice(ret, func(i, j int) bool { return ret[i].Ref < ret[j].Ref })
	var b strings.Builder
	for _, e := range ents {
		fmt.Fprintf(&b, "entity|%s|%s|%d|%s|%s|%s|%s|%t|%t|%s|%s|%s|%s\n", e.Ref(), e.Name, e.Version, e.Key, e.OwnerDomain, e.Class, e.Status, e.Covered, e.TenantScoped, e.LifecycleAssignment, e.CommandBoundary, e.StreamKind, e.SourceRef)
		for _, a := range e.Aliases {
			fmt.Fprintf(&b, "alias|%s|%s\n", e.Ref(), a)
		}
		for _, i := range e.Invariants {
			fmt.Fprintf(&b, "invariant|%s|%s\n", e.Ref(), i)
		}
		for _, c := range e.ChildRefs {
			fmt.Fprintf(&b, "child|%s|%s\n", e.Ref(), c)
		}
		for _, p := range e.Properties {
			fmt.Fprintf(&b, "property|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s|%s\n", e.Ref(), p.Name, p.GoType, p.SchemaPath, p.Presence, p.Classification, p.Temporal, p.AuthorityRef, p.Correction, p.RetentionClassRef, p.Status, p.Ref(e.Key))
		}
	}
	for _, r := range rels {
		fmt.Fprintf(&b, "relationship|%s|%s|%s|%s|%t|%t|%t|%t|%s\n", r.Ref(), r.SourceEntity, r.TargetEntity, r.Cardinality, r.Exclusive, r.AllowCycles, r.TenantScoped, r.Covered, r.SourceRef)
	}
	for _, a := range auth {
		fmt.Fprintf(&b, "authority|%s|%s|%s|%s|%s|%t|%d|%s|%t\n", a.Ref, a.Kind, a.DomainScope, a.EffectiveFrom, a.Merge, a.Exclusive, a.FreshnessSeconds, a.EvidenceRef, a.Covered)
	}
	for _, r := range ret {
		fmt.Fprintf(&b, "retention|%s|%d|%s|%s|%s|%t\n", r.Ref, r.DefaultPeriodDays, r.TriggerEvent, r.DispositionOwner, r.AuthorityRef, r.Covered)
		keys := make([]string, 0, len(r.JurisdictionOverrides))
		for k := range r.JurisdictionOverrides {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "retention_override|%s|%s|%d\n", r.Ref, k, r.JurisdictionOverrides[k])
		}
	}
	return []byte(b.String())
}

func render(m *sources.Manifest, packageName, sourceDigest, generatedDigest string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gen/schemaflux/modelgen. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source digest: %s\n", sourceDigest)
	fmt.Fprintf(&b, "// Generated digest: %s (canonical template digest)\n\n", generatedDigest)
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	b.WriteString("import (\n\t\"crypto/sha256\"\n\t\"encoding/binary\"\n\t\"encoding/hex\"\n\t\"fmt\"\n\n\t\"github.com/monstercameron/human-capital-management-suite/internal/intent/lifecycle\"\n\t\"github.com/monstercameron/human-capital-management-suite/internal/kernel/values\"\n)\n\n")
	b.WriteString("// SourceDigest identifies the exact SchemaFlux source projection used to build this package.\n")
	fmt.Fprintf(&b, "const SourceDigest = %q\n", sourceDigest)
	fmt.Fprintf(&b, "const GeneratedDigest = %q\n\n", generatedDigest)
	b.WriteString("// CanonicalDigest computes a boundary-safe SHA-256 digest for generated model payload parts.\nfunc CanonicalDigest(parts ...[]byte) string {\n\th := sha256.New()\n\tfor _, p := range parts { var n [8]byte; binary.BigEndian.PutUint64(n[:], uint64(len(p))); _, _ = h.Write(n[:]); _, _ = h.Write(p) }\n\treturn \"sha256:\" + hex.EncodeToString(h.Sum(nil))\n}\n\n")
	// The generated package's digest helper is intentionally useful without
	// importing tools. Keep it small and deterministic using SHA-256.
	b.WriteString("// RegistryDigest is the source-bound registry identity.\nconst RegistryDigest = SourceDigest\n\n")
	ents := append([]sources.EntitySource(nil), m.Entities...)
	sort.Slice(ents, func(i, j int) bool { return ents[i].Ref() < ents[j].Ref() })
	for _, e := range ents {
		renderEntity(&b, e)
	}
	renderRegistry(&b, m, ents)
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("modelgen: format generated Go: %w", err)
	}
	return formatted, nil
}

func renderEntity(b *bytes.Buffer, e sources.EntitySource) {
	fmt.Fprintf(b, "// %s is the typed SchemaFlux projection of %s.\n", e.Name, e.Ref())
	fmt.Fprintf(b, "type %s struct {\n", e.Name)
	for _, p := range e.Properties {
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", exported(p.Name), goType(p.GoType), p.Name)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "func (v %s) Validate() error {\n", e.Name)
	for _, p := range e.Properties {
		if p.Status != "ACTIVE" && e.Covered {
			continue
		}
		if p.Presence == "REQUIRED" {
			renderRequired(b, "v."+exported(p.Name), p.GoType, e.Name+"."+p.Name)
		}
	}
	b.WriteString("\treturn nil\n}\n\n")
}

func renderRequired(b *bytes.Buffer, expr, typ, path string) {
	switch typ {
	case "string", "lifecycle.StateID":
		fmt.Fprintf(b, "\tif %s == \"\" { return fmt.Errorf(%q) }\n", expr, path+": required value is empty")
	case "uint32":
		fmt.Fprintf(b, "\tif %s == 0 { return fmt.Errorf(%q) }\n", expr, path+": required value is zero")
	case "bool":
		fmt.Fprintf(b, "\tif !%s { return fmt.Errorf(%q) }\n", expr, path+": required value is false")
	case "[]string":
		fmt.Fprintf(b, "\tif len(%s) == 0 { return fmt.Errorf(%q) }\n", expr, path+": required list is empty")
	default:
		fmt.Fprintf(b, "\tif err := %s.Validate(); err != nil { return fmt.Errorf(%q+\": %%w\", err) }\n", expr, path)
	}
}

func renderRegistry(b *bytes.Buffer, m *sources.Manifest, ents []sources.EntitySource) {
	b.WriteString("// PropertyDescriptor records the source-level contract for one field.\ntype PropertyDescriptor struct { Ref, Entity, Name, GoType, SchemaPath, Presence, Classification, Temporal, AuthorityRef, Correction, RetentionClassRef, Status string }\n")
	b.WriteString("// EntityDescriptor records ownership and lifecycle metadata.\ntype EntityDescriptor struct { Ref, Name, Key, OwnerDomain, Class, Status, LifecycleAssignment string; TenantScoped, Covered bool; Properties []PropertyDescriptor }\n")
	b.WriteString("// RelationDescriptor records relationship endpoints and constraints.\ntype RelationDescriptor struct { Ref, SourceEntity, TargetEntity, Cardinality string; Exclusive, AllowCycles, TenantScoped, Covered bool }\n")
	b.WriteString("// AuthorityDescriptor records source ownership metadata.\ntype AuthorityDescriptor struct { Ref, Kind, DomainScope, EffectiveFrom, Merge, EvidenceRef string; Exclusive, Covered bool; FreshnessSeconds uint32 }\n")
	b.WriteString("// RetentionDescriptor records evidence-retention metadata.\ntype RetentionDescriptor struct { Ref, TriggerEvent, DispositionOwner, AuthorityRef string; DefaultPeriodDays uint32; JurisdictionOverrides map[string]uint32; Covered bool }\n\n")
	b.WriteString("var Entities = []EntityDescriptor{\n")
	for _, e := range ents {
		fmt.Fprintf(b, "\t{Ref:%q, Name:%q, Key:%q, OwnerDomain:%q, Class:%q, Status:%q, LifecycleAssignment:%q, TenantScoped:%t, Covered:%t, Properties: []PropertyDescriptor{\n", e.Ref(), e.Name, e.Key, e.OwnerDomain, e.Class, e.Status, e.LifecycleAssignment, e.TenantScoped, e.Covered)
		for _, p := range e.Properties {
			fmt.Fprintf(b, "\t\t{Ref:%q, Entity:%q, Name:%q, GoType:%q, SchemaPath:%q, Presence:%q, Classification:%q, Temporal:%q, AuthorityRef:%q, Correction:%q, RetentionClassRef:%q, Status:%q},\n", p.Ref(e.Key), e.Ref(), p.Name, p.GoType, p.SchemaPath, p.Presence, p.Classification, p.Temporal, p.AuthorityRef, p.Correction, p.RetentionClassRef, p.Status)
		}
		b.WriteString("\t}},\n")
	}
	b.WriteString("}\n\nvar Relationships = []RelationDescriptor{\n")
	rels := append([]sources.RelationshipSource(nil), m.Relationships...)
	sort.Slice(rels, func(i, j int) bool { return rels[i].Ref() < rels[j].Ref() })
	for _, r := range rels {
		fmt.Fprintf(b, "\t{Ref:%q, SourceEntity:%q, TargetEntity:%q, Cardinality:%q, Exclusive:%t, AllowCycles:%t, TenantScoped:%t, Covered:%t},\n", r.Ref(), r.SourceEntity, r.TargetEntity, r.Cardinality, r.Exclusive, r.AllowCycles, r.TenantScoped, r.Covered)
	}
	b.WriteString("}\n\n")
	b.WriteString("// GeneratedRegistry is the immutable SchemaFlux registry publication.\ntype GeneratedRegistry struct { Entities []EntityDescriptor; Relationships []RelationDescriptor; Authorities []AuthorityDescriptor; Retentions []RetentionDescriptor; Digest string }\n\n")
	auth := append([]sources.AuthoritySource(nil), m.Authorities...)
	sort.Slice(auth, func(i, j int) bool { return auth[i].Ref < auth[j].Ref })
	b.WriteString("var Authorities = []AuthorityDescriptor{\n")
	for _, a := range auth {
		fmt.Fprintf(b, "\t{Ref:%q, Kind:%q, DomainScope:%q, EffectiveFrom:%q, Merge:%q, EvidenceRef:%q, Exclusive:%t, Covered:%t, FreshnessSeconds:%d},\n", a.Ref, a.Kind, a.DomainScope, a.EffectiveFrom, a.Merge, a.EvidenceRef, a.Exclusive, a.Covered, a.FreshnessSeconds)
	}
	b.WriteString("}\n\nvar Retentions = []RetentionDescriptor{\n")
	ret := append([]sources.RetentionClassSource(nil), m.Retentions...)
	sort.Slice(ret, func(i, j int) bool { return ret[i].Ref < ret[j].Ref })
	for _, r := range ret {
		keys := make([]string, 0, len(r.JurisdictionOverrides))
		for k := range r.JurisdictionOverrides {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(b, "\t{Ref:%q, TriggerEvent:%q, DispositionOwner:%q, AuthorityRef:%q, DefaultPeriodDays:%d, Covered:%t, JurisdictionOverrides: map[string]uint32{", r.Ref, r.TriggerEvent, r.DispositionOwner, r.AuthorityRef, r.DefaultPeriodDays, r.Covered)
		for _, k := range keys {
			fmt.Fprintf(b, "%q:%d,", k, r.JurisdictionOverrides[k])
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n\nvar Registry = GeneratedRegistry{Entities: Entities, Relationships: Relationships, Authorities: Authorities, Retentions: Retentions, Digest: RegistryDigest}\n\n")
	b.WriteString("// ValidateRegistry checks generated descriptors without publishing mutation authority.\nfunc ValidateRegistry() error {\n\tfor _, e := range Entities {\n\t\tif e.Ref == \"\" || e.Name == \"\" || e.Key == \"\" || e.OwnerDomain == \"\" || e.Class == \"\" || e.Status == \"\" || e.LifecycleAssignment == \"\" { return fmt.Errorf(\"invalid entity descriptor %s\", e.Ref) }\n\t\tfor _, p := range e.Properties { if p.Ref == \"\" || p.GoType == \"\" || p.SchemaPath == \"\" || p.Presence == \"\" || p.AuthorityRef == \"\" || p.RetentionClassRef == \"\" { return fmt.Errorf(\"invalid property descriptor %s\", p.Ref) } }\n\t}\n\tfor _, r := range Relationships { if r.Ref == \"\" || r.SourceEntity == \"\" || r.TargetEntity == \"\" || r.Cardinality == \"\" { return fmt.Errorf(\"invalid relationship descriptor %s\", r.Ref) } }\n\tfor _, a := range Authorities { if a.Ref == \"\" || a.Kind == \"\" || a.DomainScope == \"\" || a.Merge == \"\" || a.EvidenceRef == \"\" { return fmt.Errorf(\"invalid authority descriptor %s\", a.Ref) } }\n\tfor _, r := range Retentions { if r.Ref == \"\" || r.TriggerEvent == \"\" || r.DispositionOwner == \"\" || r.AuthorityRef == \"\" || (r.DefaultPeriodDays == 0 && len(r.JurisdictionOverrides) == 0) { return fmt.Errorf(\"invalid retention descriptor %s\", r.Ref) } }\n\treturn nil\n}\n")
	b.WriteString("// Entity resolves a generated entity descriptor by canonical reference.\nfunc Entity(ref string) (EntityDescriptor, bool) { for _, e := range Entities { if e.Ref == ref { return e, true } }; return EntityDescriptor{}, false }\n\n// Relationship resolves a generated relationship descriptor by reference.\nfunc Relationship(ref string) (RelationDescriptor, bool) { for _, r := range Relationships { if r.Ref == ref { return r, true } }; return RelationDescriptor{}, false }\n")
}

func goType(t string) string { return strings.Trim(t, "\"") }

func exported(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		if r == '_' || r == '-' || r == '.' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	name := b.String()
	switch name {
	case "Id":
		return "ID"
	case "Ids":
		return "IDs"
	case "Url":
		return "URL"
	case "Uri":
		return "URI"
	}
	return name
}
