package schemaflux

import (
	"fmt"
	"strings"
)

// QualificationRecord is the TOOL-004 decision record: the qualification
// fixture's result for github.com/monstercameron/schemaflux, the fallback it
// selects, and the evidence from one concrete fixture run.
type QualificationRecord struct {
	SchemaFluxVersion string

	DefinitionsCompiled  int
	CapabilityEntries    int
	NetworkCallsMade     int
	RunsCompared         int
	ByteIdentical        bool
	CrossCheckMismatches int
	ContentDigest        string
}

// YAML renders the qualification record deterministically, by hand, for the
// same reason DefinitionSourceManifest.YAML does: stable field order
// independent of struct reflection order.
func (r QualificationRecord) YAML() []byte {
	var b strings.Builder
	b.WriteString("# Generated by tools/gen/schemaflux (TOOL-004). DO NOT EDIT BY HAND.\n")
	b.WriteString("#\n")
	b.WriteString("# Re-run: go test -run TestSchemaFluxOfflineFixture ./tools/gen/schemaflux/...\n")
	b.WriteString("schema_version: 1\n")
	b.WriteString("todo: TOOL-004\n")
	b.WriteString("decision: PROTOC_FALLBACK\n")
	b.WriteString("generator: tools/gen/schemaflux (native deterministic Go compiler; no protoc\n")
	b.WriteString("  invocation needed because these are structured YAML definitions, not .proto\n")
	b.WriteString("  messages — see doc.go)\n")
	b.WriteString("schemaflux:\n")
	fmt.Fprintf(&b, "  package: github.com/monstercameron/schemaflux\n  version: %s\n", r.SchemaFluxVersion)
	b.WriteString("  qualification_result: DISQUALIFIED\n")
	b.WriteString("  reason: >\n")
	b.WriteString("    Every public entry point (Extracting, Generating, Transforming, Choosing,\n")
	b.WriteString("    Summarizing, and roughly ninety more builders in schemaflux.go) is a typed\n")
	b.WriteString("    LLM operation: it calls a configured model provider (OpenAI by default)\n")
	b.WriteString("    through internal/llm, which builds a plain &http.Client{} with no offline\n")
	b.WriteString("    path once a real provider is selected. There is no function whose contract\n")
	b.WriteString("    is \"compile a structured definition file into a Go registry, markdown\n")
	b.WriteString("    catalog or JSON fixture without a model call.\" The library's own\n")
	b.WriteString("    deliberate offline stand-in (SCHEMAFLUX_PROVIDER=local /\n")
	b.WriteString("    Client.WithMockProvider) answers every operation with shape-correct but,\n")
	b.WriteString("    by internal/llm/mockshape.go's own words, \"obviously synthetic\" filler\n")
	b.WriteString("    unrelated to the real input; internal/api/client/client.go separately\n")
	b.WriteString("    documents that falling back to it silently (no API key, no explicit\n")
	b.WriteString("    request) would be indistinguishable from a working deployment until\n")
	b.WriteString("    someone reads the output, which is why it must be asked for explicitly.\n")
	b.WriteString("    Either way it rules SchemaFlux out for real generation.\n")
	b.WriteString("  evidence:\n")
	b.WriteString("    - \"TestSchemaFluxOfflineFixture/SchemaFluxRequiresNetworkForRealGeneration proves a non-mock generation attempt dials out through http.DefaultTransport (blocked by a test transport; the attempt still counts as a dial, observed making 4 attempts with backoff before failing).\"\n")
	b.WriteString("    - \"TestSchemaFluxOfflineFixture/SchemaFluxOfflineStandInIsUnusablePlaceholderText proves the mock/local provider path answers with canned, shape-correct filler (e.g. {'result': 'transformed data', 'success': true}) that never reflects the real input, not structured content derived from it.\"\n")
	b.WriteString("    - \"schemafluxtest's cassette Player replays a previously recorded model answer; it cannot originate one, so it is a unit-test double for code that calls SchemaFlux, not a definition compiler.\"\n")
	b.WriteString("  fallback:\n")
	b.WriteString("    selected: true\n")
	b.WriteString("    kind: PROTOC_STYLE_DETERMINISTIC_GO_COMPILER\n")
	b.WriteString("    description: >\n")
	b.WriteString("      Definitions stay declared as structured source (the fourteen YAML files\n")
	b.WriteString("      under schema/schemaflux/business_intents/v1, matched against the\n")
	b.WriteString("      Protobuf hcmnext.intents.v1.IntentDefinition message shape) and are\n")
	b.WriteString("      compiled by a small offline, model-free Go program in this package\n")
	b.WriteString("      (loader.go, resolve.go, generate.go) — the same \"generation is\n")
	b.WriteString("      deterministic tooling, not an AI call\" posture the constitution asks\n")
	b.WriteString("      protoc + protoc-gen-go to provide for Protobuf. The registry ships as a\n")
	b.WriteString("      compiled-in Go table either way (capability-registry-and-lifecycle.md\n")
	b.WriteString("      BOOTSTRAP profile); the hand-authored table in\n")
	b.WriteString("      internal/intent/definitions already satisfies that requirement today\n")
	b.WriteString("      (TOOL-002/TOOL-003) and this package cross-checks against it rather than\n")
	b.WriteString("      replacing it.\n")
	b.WriteString("fixture:\n")
	fmt.Fprintf(&b, "  definitions_compiled: %d\n", r.DefinitionsCompiled)
	fmt.Fprintf(&b, "  capability_manifest_entries_compiled: %d\n", r.CapabilityEntries)
	fmt.Fprintf(&b, "  network_calls_during_fallback_generation: %d\n", r.NetworkCallsMade)
	fmt.Fprintf(&b, "  runs_compared: %d\n", r.RunsCompared)
	fmt.Fprintf(&b, "  byte_identical: %t\n", r.ByteIdentical)
	fmt.Fprintf(&b, "  cross_check_mismatches_against_internal_intent_definitions: %d\n", r.CrossCheckMismatches)
	fmt.Fprintf(&b, "  content_digest: %s\n", r.ContentDigest)
	b.WriteString("  content_digest_scope: >\n")
	b.WriteString("    sha256 over the length-prefixed concatenation of the generated registry Go\n")
	b.WriteString("    source, markdown catalog and JSON fixture bytes, produced by\n")
	b.WriteString("    tools/gen/schemaflux from the pinned inputs\n")
	b.WriteString("    (schema/schemaflux/business_intents/v1/*.yaml plus\n")
	b.WriteString("    tools/gen/schemaflux/testdata/capability_manifest.yaml). Recomputed fresh\n")
	b.WriteString("    by TestSchemaFluxOfflineFixture on every run; not expected to survive an\n")
	b.WriteString("    unrelated cosmetic reformat of this file by a formatter.\n")
	return []byte(b.String())
}
