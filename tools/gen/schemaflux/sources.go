package schemaflux

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

// DefinitionSourceManifest is the MSRC-001 deliverable: one source manifest
// enumerating exactly the fourteen business-intent definitions and the P1A
// capability manifest entries the qualified generator compiles — nothing
// else. A planning entity outside that covered set is never enumerated here.
type DefinitionSourceManifest struct {
	Definitions        []DefinitionSourceEntry
	CapabilityManifest []CapabilitySourceEntry
}

// DefinitionSourceEntry is one of the fourteen definitions' source record:
// its source file, stable ID, owner and a content digest, per MSRC-001's
// RED ("lacks a source file, stable ID, owner and storage disposition").
type DefinitionSourceEntry struct {
	IntentTypeID string
	Version      uint32
	SourceFile   string
	OwnerPlane   string
	OwnerDomain  string
	KernelFamily string
	Digest       string
}

// CapabilitySourceEntry is one P1A capability manifest entry's source record.
type CapabilitySourceEntry struct {
	ID                 string
	Version            uint32
	SourceFile         string
	OwnerDomain        string
	StorageDisposition string
	Digest             string
}

// definitionDigest hashes exactly the fields a source manifest attests for
// one definition, not the raw file bytes: manager_change.yaml holds one
// definition but promotion.yaml holds thirteen sharing one file, so a
// per-definition digest — not a per-file digest — is the only one that
// identifies one definition's own content.
func definitionDigest(d Definition) string {
	var b strings.Builder
	fmt.Fprintf(&b, "intent_type_id=%s\n", d.IntentTypeID)
	fmt.Fprintf(&b, "version=%d\n", d.Version)
	fmt.Fprintf(&b, "display_name=%s\n", d.DisplayName)
	fmt.Fprintf(&b, "owner_plane=%s\n", d.OwnerPlane)
	fmt.Fprintf(&b, "owner_domain=%s\n", d.OwnerDomain)
	fmt.Fprintf(&b, "kernel_family=%s\n", d.KernelFamily)
	fmt.Fprintf(&b, "input_schema_ref=%s\n", d.InputSchemaRef)
	fmt.Fprintf(&b, "result_schema_ref=%s\n", d.ResultSchemaRef)
	fmt.Fprintf(&b, "required_capabilities=%s\n", strings.Join(d.RequiredCapabilities, ","))
	return Digest([]byte(b.String()))
}

func capabilityDigest(c CapabilityManifestEntry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "id=%s\n", c.ID)
	fmt.Fprintf(&b, "version=%d\n", c.Version)
	fmt.Fprintf(&b, "owner_domain=%s\n", c.OwnerDomain)
	fmt.Fprintf(&b, "effect_class=%s\n", c.EffectClass)
	fmt.Fprintf(&b, "read_domains=%s\n", strings.Join(c.ReadDomains, ","))
	fmt.Fprintf(&b, "storage_disposition=%s\n", c.StorageDisposition)
	return Digest([]byte(b.String()))
}

// BuildDefinitionSourceManifest builds the MSRC-001 manifest from a compiled
// catalog. It reports exact counts by construction: len(Definitions) and
// len(CapabilityManifest) are the manifest's own denominators, matching
// internal/intent/definitions.go's "only denominator is the length of this
// table" posture.
func BuildDefinitionSourceManifest(catalog *Catalog, repoRelativeSourceFile func(absolute string) string) DefinitionSourceManifest {
	m := DefinitionSourceManifest{}
	for _, d := range catalog.Definitions {
		m.Definitions = append(m.Definitions, DefinitionSourceEntry{
			IntentTypeID: d.IntentTypeID,
			Version:      d.Version,
			SourceFile:   repoRelativeSourceFile(d.SourceFile),
			OwnerPlane:   d.OwnerPlane,
			OwnerDomain:  d.OwnerDomain,
			KernelFamily: d.KernelFamily,
			Digest:       definitionDigest(d),
		})
	}
	for _, c := range catalog.CapabilityManifest {
		m.CapabilityManifest = append(m.CapabilityManifest, CapabilitySourceEntry{
			ID:                 c.ID,
			Version:            c.Version,
			SourceFile:         repoRelativeSourceFile(c.SourceFile),
			OwnerDomain:        c.OwnerDomain,
			StorageDisposition: c.StorageDisposition,
			Digest:             capabilityDigest(c),
		})
	}
	return m
}

// YAML renders the manifest deterministically by hand (not through
// gopkg.in/yaml.v3's marshaler) so field order in the file matches this
// function's own order rather than Go struct-tag reflection order, keeping
// the output stable if the struct's field order is ever refactored for
// unrelated reasons.
func (m DefinitionSourceManifest) YAML() []byte {
	defs := append([]DefinitionSourceEntry(nil), m.Definitions...)
	sort.Slice(defs, func(i, j int) bool { return defs[i].IntentTypeID < defs[j].IntentTypeID })
	caps := append([]CapabilitySourceEntry(nil), m.CapabilityManifest...)
	sort.Slice(caps, func(i, j int) bool { return caps[i].ID < caps[j].ID })

	var b strings.Builder
	b.WriteString("# Generated by tools/gen/schemaflux (MSRC-001). DO NOT EDIT BY HAND.\n")
	b.WriteString("#\n")
	b.WriteString("# One source manifest for exactly the fourteen business-intent definitions\n")
	b.WriteString("# and the P1A capability manifest entries the qualified generator compiles.\n")
	b.WriteString("# Planning entities outside that covered set are not enumerated here.\n")
	b.WriteString("schema_version: 1\n")
	fmt.Fprintf(&b, "counts:\n  definitions: %d\n  capability_manifests: %d\n", len(defs), len(caps))
	b.WriteString("definitions:\n")
	for _, d := range defs {
		fmt.Fprintf(&b, "  - intent_type_id: %s\n", d.IntentTypeID)
		fmt.Fprintf(&b, "    version: %d\n", d.Version)
		fmt.Fprintf(&b, "    source_file: %s\n", forwardSlash(d.SourceFile))
		fmt.Fprintf(&b, "    owner_plane: %s\n", d.OwnerPlane)
		fmt.Fprintf(&b, "    owner_domain: %s\n", d.OwnerDomain)
		fmt.Fprintf(&b, "    kernel_family: %s\n", d.KernelFamily)
		fmt.Fprintf(&b, "    digest: %s\n", d.Digest)
	}
	b.WriteString("capability_manifests:\n")
	for _, c := range caps {
		fmt.Fprintf(&b, "  - id: %s\n", c.ID)
		fmt.Fprintf(&b, "    version: %d\n", c.Version)
		fmt.Fprintf(&b, "    source_file: %s\n", forwardSlash(c.SourceFile))
		fmt.Fprintf(&b, "    owner_domain: %s\n", c.OwnerDomain)
		fmt.Fprintf(&b, "    storage_disposition: %s\n", c.StorageDisposition)
		fmt.Fprintf(&b, "    digest: %s\n", c.Digest)
	}
	return []byte(b.String())
}

// forwardSlash normalizes a path to forward slashes so the checked-in
// manifest reads the same on Windows and Unix (repoRelativeSourceFile
// already strips the machine-specific absolute prefix; this strips the
// remaining OS-specific separator).
func forwardSlash(p string) string {
	return strings.ReplaceAll(p, "\\", "/")
}

// WriteFile writes b to path, creating no parent directories: callers pass a
// path whose directory (definitions/generation) already exists in this
// repository.
func WriteFile(path string, b []byte) error {
	return os.WriteFile(path, b, 0o644)
}
