// entityDigest hashes exactly the fields a manifest attests for one entity —
// its identity, ownership, classification and property set — using the
// sibling business_intents pipeline's own [schemaflux.Digest], so every
// SchemaFlux source manifest in this repository shares one digest
// convention rather than each subpackage inventing its own.
func entityDigest(e EntitySource) string {
	var b strings.Builder
	fmt.Fprintf(&b, "name=%s\n", e.Name)
	fmt.Fprintf(&b, "version=%d\n", e.Version)
	fmt.Fprintf(&b, "key=%s\n", e.Key)
	fmt.Fprintf(&b, "owner_domain=%s\n", e.OwnerDomain)
	fmt.Fprintf(&b, "class=%s\n", e.Class)
	fmt.Fprintf(&b, "status=%s\n", e.Status)
	fmt.Fprintf(&b, "lifecycle_assignment=%s\n", e.LifecycleAssignment)
	for _, p := range e.Properties {
		fmt.Fprintf(&b, "property=%s|%s|%s|%s\n", p.Name, p.GoType, p.Presence, p.Status)
	}
	return schemaflux.Digest([]byte(b.String()))
}

func relationshipDigest(r RelationshipSource) string {
	var b strings.Builder
	fmt.Fprintf(&b, "name=%s\n", r.Name)
	fmt.Fprintf(&b, "version=%d\n", r.Version)
	fmt.Fprintf(&b, "source_entity=%s\n", r.SourceEntity)
	fmt.Fprintf(&b, "target_entity=%s\n", r.TargetEntity)
	fmt.Fprintf(&b, "cardinality=%s\n", r.Cardinality)
	return schemaflux.Digest([]byte(b.String()))
}

// Relativize returns a copy of m whose every SourceFile is rewritten
// relative to root, mirroring
// tools/gen/schemaflux.BuildDefinitionSourceManifest's repoRelativeSourceFile
// callback: a checked-in manifest must read the same on every machine, and
// an absolute, host-specific path defeats that the moment it is generated on
// a different checkout location.
func (m Manifest) Relativize(root string) Manifest {
	rel := func(abs string) string {
		r, err := filepath.Rel(root, abs)
		if err != nil {
			return abs
		}
		return r
	}
	out := m
	out.Entities = make([]EntitySource, len(m.Entities))
	for i, e := range m.Entities {
		e.SourceFile = rel(e.SourceFile)
		out.Entities[i] = e
	}
	out.Relationships = make([]RelationshipSource, len(m.Relationships))
	for i, r := range m.Relationships {
		r.SourceFile = rel(r.SourceFile)
		out.Relationships[i] = r
	}
	out.Authorities = make([]AuthoritySource, len(m.Authorities))
	for i, a := range m.Authorities {
		a.SourceFile = rel(a.SourceFile)
		out.Authorities[i] = a
	}
	out.Retentions = make([]RetentionClassSource, len(m.Retentions))
	for i, r := range m.Retentions {
		r.SourceFile = rel(r.SourceFile)
		out.Retentions[i] = r
	}
	return out
}

// YAML renders the manifest deterministically by hand, matching
// tools/gen/schemaflux.DefinitionSourceManifest.YAML's convention of
// explicit field order over reflection-driven marshaling.
func (m Manifest) YAML() []byte {
	var b strings.Builder
	b.WriteString("# Generated by tools/gen/schemaflux/sources (MSRC-002..MSRC-005). DO NOT EDIT BY HAND.\n")
	b.WriteString("#\n")
	b.WriteString("# One compiled manifest over schema/schemaflux/metamodel/v1/metamodel.yaml,\n")
	b.WriteString("# schema/schemaflux/registries/v1/registries.yaml and every\n")
	b.WriteString("# schema/schemaflux/entities/v1/*.yaml family source.\n")
	b.WriteString("schema_version: 1\n")
	fmt.Fprintf(&b, "counts:\n  entities: %d\n  relationships: %d\n  authorities: %d\n  retention_classes: %d\n",
		len(m.Entities), len(m.Relationships), len(m.Authorities), len(m.Retentions))

	b.WriteString("family_counts:\n")
	families := make([]string, 0, len(m.FamilyCounts))
	for f := range m.FamilyCounts {
		families = append(families, f)
	}
	sortStrings(families)
	for _, f := range families {
		fmt.Fprintf(&b, "  %s: %d\n", f, m.FamilyCounts[f])
	}

	b.WriteString("entities:\n")
	for _, e := range m.Entities {
		fmt.Fprintf(&b, "  - ref: %s\n", e.Ref())
		fmt.Fprintf(&b, "    family: %s\n", e.Family)
		fmt.Fprintf(&b, "    key: %s\n", e.Key)
		fmt.Fprintf(&b, "    owner_domain: %s\n", e.OwnerDomain)
		fmt.Fprintf(&b, "    class: %s\n", e.Class)
		fmt.Fprintf(&b, "    status: %s\n", e.Status)
		fmt.Fprintf(&b, "    covered: %v\n", e.Covered)
		fmt.Fprintf(&b, "    property_count: %d\n", len(e.Properties))
		fmt.Fprintf(&b, "    source_file: %s\n", forwardSlash(e.SourceFile))
		fmt.Fprintf(&b, "    digest: %s\n", entityDigest(e))
	}

	b.WriteString("relationships:\n")
	for _, r := range m.Relationships {
		fmt.Fprintf(&b, "  - ref: %s\n", r.Ref())
		fmt.Fprintf(&b, "    family: %s\n", r.Family)
		fmt.Fprintf(&b, "    source_entity: %s\n", r.SourceEntity)
		fmt.Fprintf(&b, "    target_entity: %s\n", r.TargetEntity)
		fmt.Fprintf(&b, "    covered: %v\n", r.Covered)
		fmt.Fprintf(&b, "    digest: %s\n", relationshipDigest(r))
	}

	b.WriteString("authorities:\n")
	for _, a := range m.Authorities {
		fmt.Fprintf(&b, "  - ref: %s\n", a.Ref)
		fmt.Fprintf(&b, "    covered: %v\n", a.Covered)
	}
	b.WriteString("retention_classes:\n")
	for _, r := range m.Retentions {
		fmt.Fprintf(&b, "  - ref: %s\n", r.Ref)
		fmt.Fprintf(&b, "    covered: %v\n", r.Covered)
	}
	return []byte(b.String())
}

func forwardSlash(p string) string { return strings.ReplaceAll(p, "\\", "/") }

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j-1] > s[j]; j-- {
			s[j-1], s[j] = s[j], s[j-1]
		}
	}
}

// WriteFile writes b to path.
func WriteFile(path string, b []byte) error {
	return os.WriteFile(path, b, 0o644)
}
