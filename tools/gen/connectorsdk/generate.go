package connectorsdk

import (
	"fmt"
	"sort"
	"strings"
	"unicode"
)

type Object struct{ Name, GoType, Version string }
type Manifest struct {
	Package string
	Objects []Object
}

// Render returns stable Go source for the generated typed client facade.
// Duplicate or incomplete objects are rejected so incompatible adapters cannot
// be accidentally generated from an ambiguous manifest.
func Render(m Manifest) ([]byte, error) {
	if m.Package == "" {
		return nil, fmt.Errorf("package is required")
	}
	seen := map[string]bool{}
	for _, o := range m.Objects {
		if o.Name == "" || o.GoType == "" || o.Version == "" {
			return nil, fmt.Errorf("object fields are required")
		}
		if seen[o.Name] {
			return nil, fmt.Errorf("duplicate object %q", o.Name)
		}
		seen[o.Name] = true
		if exported(o.Name) == "" {
			return nil, fmt.Errorf("object %q has no valid Go identifier", o.Name)
		}
	}
	objects := append([]Object(nil), m.Objects...)
	sort.Slice(objects, func(i, j int) bool { return objects[i].Name < objects[j].Name })
	var b strings.Builder
	b.WriteString("// Code generated by connectorsdk; DO NOT EDIT.\n\npackage " + m.Package + "\n\nimport (\n\t\"context\"\n\t\"time\"\n\n\tadapter \"github.com/monstercameron/hcm-next/internal/connectivity/adapter\"\n)\n\n")
	for _, o := range objects {
		n := exported(o.Name)
		b.WriteString(fmt.Sprintf("// %s is the typed %s connector client.\ntype %s struct { Client adapter.Typed[%s] }\n\n", n, o.Name, n, o.GoType))
		b.WriteString(fmt.Sprintf("func (c %s) Read(ctx context.Context, cursor string, limit int, since time.Time) (adapter.Page[%s], error) { return c.Client.Read(ctx, cursor, limit, since) }\n", n, o.GoType))
		b.WriteString(fmt.Sprintf("func (c %s) Write(ctx context.Context, value %s, key, expected string) (adapter.WriteResult[%s], error) { return c.Client.Write(ctx, value, key, expected) }\n", n, o.GoType, o.GoType))
		b.WriteString(fmt.Sprintf("func (c %s) Observe(ctx context.Context, id string) (adapter.Observation[%s], error) { return c.Client.Observe(ctx, id) }\n", n, o.GoType))
		b.WriteString(fmt.Sprintf("func (c %s) Subscribe(ctx context.Context, cursor string) (adapter.Subscription[%s], error) { return c.Client.Subscribe(ctx, cursor) }\n\n", n, o.GoType))
	}
	return []byte(b.String()), nil
}
func exported(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			if up && r >= 'a' && r <= 'z' {
				r -= 32
			}
			b.WriteRune(r)
			up = false
		} else {
			up = true
		}
	}
	return b.String()
}
