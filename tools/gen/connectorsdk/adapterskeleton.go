package connectorsdk

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/monstercameron/human-capital-management-suite/internal/connectivity/spi"
)

// AdapterSkeleton describes one connector adapter to scaffold from a declared
// [spi.AdapterManifest]: the Go package and exported type name the generated
// skeleton and conformance test are written into.
//
// This is deliberately a second, independent entry point from [Render]/
// [Manifest]: [Render] targets internal/connectivity/adapter's broader,
// generic Read/Write/Observe/Subscribe surface, which this release's
// [spi.Adapter] SPI does not expose. RenderAdapterSkeleton and
// RenderConformanceTest target [spi.Adapter] instead, so a generated
// connector can never compile against a write-capable surface by accident.
type AdapterSkeleton struct {
	// Package is the Go package name both generated files declare.
	Package string
	// TypeName is the exported Go identifier for the generated adapter
	// struct.
	TypeName string
	// Manifest is the declared manifest the skeleton's Describe method
	// returns (with GeneratedAt stamped fresh on every call; the literal
	// value here supplies every other field).
	Manifest spi.AdapterManifest
}

func (s AdapterSkeleton) validate() error {
	if strings.TrimSpace(s.Package) == "" {
		return fmt.Errorf("package is required")
	}
	if strings.TrimSpace(s.TypeName) == "" {
		return fmt.Errorf("type name is required")
	}
	if exported(s.TypeName) != s.TypeName {
		return fmt.Errorf("type name %q is not an exported Go identifier", s.TypeName)
	}
	return s.Manifest.Validate()
}

// RenderAdapterSkeleton returns stable Go source for a connector adapter
// struct that compiles against [spi.Adapter]: Describe and Probe are
// implemented from the declared manifest, and ReadSnapshot/ObserveChanges are
// left as explicit TODO stubs that refuse with connectivity.ErrUnsupported
// until a connector author fills in the vendor-specific transport.
//
// The manifest is validated before rendering, so a skeleton can never be
// generated for a manifest that (for example) declares write capability as
// already active: [spi.AdapterManifest.Validate] rejects that before this
// function ever emits a line of source.
func RenderAdapterSkeleton(s AdapterSkeleton) ([]byte, error) {
	if err := s.validate(); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by connectorsdk; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", s.Package)
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	b.WriteString("\t\"time\"\n\n")
	b.WriteString("\t\"github.com/monstercameron/human-capital-management-suite/internal/connectivity\"\n")
	b.WriteString("\t\"github.com/monstercameron/human-capital-management-suite/internal/connectivity/spi\"\n")
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "// %s is a generated connector adapter skeleton for %s %s.\n", s.TypeName, s.Manifest.Vendor, s.Manifest.Product)
	fmt.Fprintf(&b, "//\n// ReadSnapshot and ObserveChanges are stubs: fill in the vendor-specific\n// transport behind them. Describe and Probe are complete as generated.\ntype %s struct{}\n\n", s.TypeName)

	fmt.Fprintf(&b, "var _ spi.Adapter = (*%s)(nil)\n\n", s.TypeName)

	fmt.Fprintf(&b, "// Describe implements [spi.Adapter].\nfunc (a *%s) Describe(ctx context.Context) (spi.AdapterManifest, error) {\n", s.TypeName)
	b.WriteString("\tif err := spi.CheckContext(ctx); err != nil {\n\t\treturn spi.AdapterManifest{}, err\n\t}\n")
	fmt.Fprintf(&b, "\treturn %s, nil\n}\n\n", manifestLiteral(s.Manifest))

	fmt.Fprintf(&b, "// Probe implements [spi.Adapter].\nfunc (a *%s) Probe(ctx context.Context) (spi.ProbeResult, error) {\n", s.TypeName)
	b.WriteString("\tif err := spi.CheckContext(ctx); err != nil {\n\t\treturn spi.ProbeResult{}, err\n\t}\n")
	b.WriteString("\treturn spi.ProbeResult{Health: spi.HealthHealthy, CheckedAt: time.Now().UTC()}, nil\n}\n\n")

	fmt.Fprintf(&b, "// ReadSnapshot implements [spi.Adapter].\n//\n// TODO: implement the vendor-specific bounded read for %s.\nfunc (a *%s) ReadSnapshot(ctx context.Context, req connectivity.ReadRequest) (spi.Snapshot, error) {\n",
		s.Manifest.AdapterID, s.TypeName)
	fmt.Fprintf(&b, "\tif err := spi.CheckContext(ctx); err != nil {\n\t\treturn spi.Snapshot{}, err\n\t}\n\treturn spi.Snapshot{}, connectivity.Fail(%q, connectivity.ErrUnsupported, \"ReadSnapshot is not implemented yet\")\n}\n\n",
		"connectorsdk."+s.TypeName+".ReadSnapshot")

	fmt.Fprintf(&b, "// ObserveChanges implements [spi.Adapter].\n//\n// TODO: implement the vendor-specific bounded change observation for %s.\nfunc (a *%s) ObserveChanges(ctx context.Context, req spi.ObserveRequest) (spi.ChangeSet, error) {\n",
		s.Manifest.AdapterID, s.TypeName)
	fmt.Fprintf(&b, "\tif err := spi.CheckContext(ctx); err != nil {\n\t\treturn spi.ChangeSet{}, err\n\t}\n\treturn spi.ChangeSet{}, connectivity.Fail(%q, connectivity.ErrUnsupported, \"ObserveChanges is not implemented yet\")\n}\n",
		"connectorsdk."+s.TypeName+".ObserveChanges")

	return []byte(b.String()), nil
}

// RenderConformanceTest returns stable Go source for a test file that drives
// the generated skeleton through the spiconform conformance kit. It is
// emitted as a separate _test.go rather than folded into the skeleton so a
// package can regenerate its test without disturbing an author's edits to
// the skeleton file itself (which is not marked DO NOT EDIT for that reason).
func RenderConformanceTest(s AdapterSkeleton) ([]byte, error) {
	if err := s.validate(); err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by connectorsdk; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", s.Package)
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	b.WriteString("\t\"testing\"\n\n")
	b.WriteString("\t\"github.com/monstercameron/human-capital-management-suite/internal/connectivity/spi/spiconform\"\n")
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "// Test%sConformance drives %s through the whole spi.Adapter contract.\n// It fails until ReadSnapshot and ObserveChanges are implemented.\nfunc Test%sConformance(t *testing.T) {\n",
		s.TypeName, s.TypeName, s.TypeName)
	fmt.Fprintf(&b, "\ta := &%s{}\n\tspiconform.Run(t, context.Background(), a)\n}\n", s.TypeName)
	return []byte(b.String()), nil
}

// manifestLiteral renders m as a Go composite literal. Objects and
// Capabilities are rendered in sorted order so the output is deterministic
// regardless of the slice order m was declared with. GeneratedAt is
// deliberately omitted: the generated Describe method stamps it fresh on
// every call.
func manifestLiteral(m spi.AdapterManifest) string {
	var b strings.Builder
	b.WriteString("spi.AdapterManifest{\n")
	fmt.Fprintf(&b, "\t\tAdapterID: %s,\n", strconv.Quote(m.AdapterID))
	fmt.Fprintf(&b, "\t\tVendor:    %s,\n", strconv.Quote(m.Vendor))
	fmt.Fprintf(&b, "\t\tProduct:   %s,\n", strconv.Quote(m.Product))
	fmt.Fprintf(&b, "\t\tVersion:   %s,\n", strconv.Quote(m.Version))

	objects := m.SortedObjects()
	b.WriteString("\t\tObjects: []connectivity.ObjectKind{\n")
	for _, o := range objects {
		fmt.Fprintf(&b, "\t\t\t%s,\n", objectKindLiteral(o))
	}
	b.WriteString("\t\t},\n")

	caps := m.SortedCapabilities()
	b.WriteString("\t\tCapabilities: []spi.Capability{\n")
	for _, c := range caps {
		fmt.Fprintf(&b, "\t\t\t{Object: %s, Operation: %s, Version: %s},\n", objectKindLiteral(c.Object), operationLiteral(c.Operation), strconv.Quote(c.Version))
	}
	b.WriteString("\t\t},\n")

	fmt.Fprintf(&b, "\t\tBounds: connectivity.Bounds{\n")
	fmt.Fprintf(&b, "\t\t\tMaxPageSize:        %d,\n", m.Bounds.MaxPageSize)
	fmt.Fprintf(&b, "\t\t\tMaxPagesPerRun:     %d,\n", m.Bounds.MaxPagesPerRun)
	fmt.Fprintf(&b, "\t\t\tMaxRecordsPerRun:   %d,\n", m.Bounds.MaxRecordsPerRun)
	fmt.Fprintf(&b, "\t\t\tMaxRecordBytes:     %d,\n", m.Bounds.MaxRecordBytes)
	fmt.Fprintf(&b, "\t\t\tMinRequestInterval: %d,\n", int64(m.Bounds.MinRequestInterval))
	b.WriteString("\t\t},\n")

	b.WriteString("\t\tGeneratedAt: time.Now().UTC(),\n")
	b.WriteString("\t}")
	return b.String()
}

// objectKindLiteral renders the three P1A object kinds as their exported
// connectivity constants, falling back to an explicit conversion for any
// future kind so this never silently drops a value.
func objectKindLiteral(o spi.ObjectKind) string {
	switch o {
	case "WORKER":
		return "connectivity.ObjectWorker"
	case "POSITION":
		return "connectivity.ObjectPosition"
	case "COMPENSATION":
		return "connectivity.ObjectCompensation"
	default:
		return "connectivity.ObjectKind(" + strconv.Quote(string(o)) + ")"
	}
}

// operationLiteral renders a spi.Operation as its exported constant.
func operationLiteral(op spi.Operation) string {
	switch op {
	case spi.OpRead:
		return "spi.OpRead"
	case spi.OpObserve:
		return "spi.OpObserve"
	case spi.OpWrite:
		return "spi.OpWrite"
	default:
		return "spi.Operation(" + strconv.Quote(string(op)) + ")"
	}
}
